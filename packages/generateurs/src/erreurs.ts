/** Temps reconnu dans un libellé (« imparfait de l’indicatif », « futur simple »…). */
function temps(libelle: string): string {
  const t = libelle.toLowerCase();
  for (const [motif, nom] of [
    ['conditionnel passé', 'cond-passe'], ['conditionnel', 'cond'], ['subjonctif passé', 'subj-passe'], ['subjonctif', 'subj'],
    ['futur antérieur', 'fa'], ['futur', 'futur'], ['passé antérieur', 'pa'], ['passé composé', 'pc'], ['passé simple', 'ps'],
    ['plus-que-parfait', 'pqp'], ['imparfait', 'imp'], ['présent', 'present'], ['impératif', 'imperatif'],
  ] as const) if (t.includes(motif)) return nom;
  return t;
}
const CONFUSIONS_TEMPS: Record<string, string> = Object.fromEntries(([
  ['futur', 'cond', 'futur-conditionnel'], ['fa', 'cond-passe', 'futur-conditionnel'], ['imp', 'ps', 'imparfait-passe-simple'],
  ['imp', 'cond', 'imparfait-conditionnel'], ['present', 'ps', 'passe-simple-present'], ['present', 'subj', 'subjonctif-indicatif'],
  ['pc', 'subj-passe', 'subjonctif-indicatif'], ['subj', 'subj-passe', 'subjonctif-present-passe'], ['pqp', 'pa', 'auxiliaire-temps-confondu'],
  ['pc', 'pqp', 'auxiliaire-temps-confondu'], ['pa', 'fa', 'auxiliaire-temps-confondu'], ['pqp', 'cond-passe', 'auxiliaire-temps-confondu'],
  ['pc', 'pa', 'auxiliaire-temps-confondu'], ['pc', 'fa', 'auxiliaire-temps-confondu'], ['cond', 'cond-passe', 'temps-simple-compose'],
  ['ps', 'pa', 'temps-simple-compose'], ['futur', 'fa', 'temps-simple-compose'], ['imp', 'pqp', 'temps-simple-compose'],
  ['present', 'pc', 'temps-simple-compose'], ['present', 'imp', 'present-imparfait'], ['present', 'futur', 'present-futur'],
  ['present', 'imperatif', 'imperatif-present'],
] as const).map(([x, y, code]) => [[x, y].sort().join('|'), code]));

/** Code d'erreur quand l'élève choisit le temps `choisi` au lieu du temps `attendu`, si la confusion est connue. */
export function confusionTemps(attendu: string, choisi: string): string | undefined {
  return CONFUSIONS_TEMPS[[temps(attendu), temps(choisi)].sort().join('|')];
}
